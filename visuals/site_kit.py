def esc(s) -> str:
    return html.escape(str(s), quote=True)


def nav_html(here: str, active: str) -> str:
    """here: the folder the page sits in ('docu'); active: '<folder>/<file>' of the current page."""
    def link(folder, path, label):
        href = path if folder == here else f"../{folder}/{path}"
        on = ' class="on"' if f"{folder}/{path}" == active else ""
        return f'<a{on} href="{href}">{esc(label)}</a>'

    rows = [("Documentation", "docu", DOCU_PAGES), ("Clusters", "docu", CLUSTER_PAGES), ("Ontology pages", "semweb", SEMWEB_PAGES)]
    return "<nav>" + "".join(
        f'<div class="grp"><span class="lab">{name}</span><span class="lnk">'
        + "".join(link(folder, p, t) for p, t in pages) + "</span></div>"
        for name, folder, pages in rows) + "</nav>"


def page(here: str, file: str, title: str, intro: str, body: str, script: str = "", head: str = "") -> str:
    """A complete page. `intro` and `body` are HTML, `title` is plain text."""
    return ("<!DOCTYPE html>\n<html lang=\"en-GB\">\n<head>\n<meta charset=\"utf-8\">\n"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n"
            f"<title>{esc(title)} · geo-lod</title>\n<link rel=\"stylesheet\" href=\"assets/site.css\">\n{head}</head>\n<body>\n<main>\n"
            f"{nav_html(here, f'{here}/{file}')}\n<h1>{esc(title)}</h1>\n<p class=\"intro\">{intro}</p>\n{body}\n</main>\n"
            f"{JS_COPY}\n{script}</body></html>\n")


def write_assets(dest: Path) -> None:
    """<dest>/assets/site.css and <dest>/assets/fonts/."""
    (dest / "assets" / "fonts").mkdir(parents=True, exist_ok=True)
    (dest / "assets" / "site.css").write_text(CSS, encoding="utf-8", newline="\n")
    for f in sorted(FONTS.glob("FiraSans-*.ttf")):
        shutil.copyfile(f, dest / "assets" / "fonts" / f.name)


def write_page(dest: Path, text: str) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(text, encoding="utf-8", newline="\n")


def png_size(path: Path) -> tuple[int, int]:
    with open(path, "rb") as fh:
        head = fh.read(24)
    return struct.unpack(">II", head[16:24])


def fig_card(imgdir: Path, name: str, label: str, caption: str, credit: str, href_dir: str = "img") -> str:
    """Figure card: PNG in the page (an SVG used as <img> cannot load the page's fonts), SVG as a download."""
    w, h = png_size(imgdir / f"{name}.png")
    return (f'<section>\n<img src="{href_dir}/{name}.png" width="{w}" height="{h}" loading="lazy" alt="{esc(caption)}">\n'
            f'<div class="row"><p class="cap"><span class="n">{esc(label)}</span>{esc(caption)}</p>'
            f'<button type="button" data-c="{esc(caption)}">Copy</button></div>\n'
            f'<p class="cr">{esc(credit)}</p>\n'
            f'<p class="dl"><a href="{href_dir}/{name}.png" download>PNG</a><a href="{href_dir}/{name}.svg" download>SVG</a></p>\n</section>')
