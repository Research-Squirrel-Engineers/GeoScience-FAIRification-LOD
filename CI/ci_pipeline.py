def add_eruption(g: Graph) -> None:
    """The CI eruption as a CRM event with its source, time-span and ages."""
    event = GEOLOD["ci_volcanic_event"]
    source_area = GEOLOD["ci_source_area"]
    span = GEOLOD["ci_eruption_timespan"]

    g.add((event, RDF.type, CRM["E5_Event"]))
    g.add((event, RDF.type, STRAT["Eruption"]))
    g.add((event, RDFS.label,
           Literal("Campanian Ignimbrite / Y-5 eruption", lang="en")))
    g.add((event, SKOS.altLabel, Literal("CI/Y-5 eruption", lang="en")))
    g.add((event, RDFS.comment, Literal(
        "The Late Pleistocene super-eruption whose tephra marks the "
        "findspots of the CI strand. The findspots are places where the "
        "tephra is present (crm:P12_occurred_in_the_presence_of); the "
        "eruption took place at its source area.", lang="en")))
    g.add((event, CRM["P7_took_place_at"], source_area))
    g.add((event, CRM["P4_has_time-span"], span))

    g.add((source_area, RDF.type, CRM["E53_Place"]))
    g.add((source_area, RDFS.label, Literal(
        "Phlegraean Fields (Campi Flegrei), source area of the CI eruption",
        lang="en")))
    g.add((source_area, SKOS.closeMatch, WD["Q755123"]))
    g.add((source_area, RDFS.comment, Literal(
        "The source area, not a vent: the exact vent of the CI eruption is "
        "discussed (De Vivo et al. 2001 propose fissures along Apennine "
        "faults rather than a ring fracture of the Campi Flegrei caldera).",
        lang="en")))

    g.add((span, RDF.type, CRM["E52_Time-Span"]))
    g.add((span, RDFS.label,
           Literal("Time-span of the CI eruption", lang="en")))

    for a in ERUPTION_AGES:
        tp = GEOLOD[f"ci_eruption_tp_{a['id']}"]
        assertion = GEOLOD[f"ci_eruption_dating_{a['id']}"]
        article = URIRef(f"https://doi.org/{a['doi']}")

        g.add((tp, RDF.type, TIME["TimePosition"]))
        g.add((tp, RDFS.label, Literal(f"{a['published']}, as ka BP", lang="en")))
        g.add((tp, TIME["numericPosition"], Literal(a["ka"], datatype=XSD.decimal)))
        g.add((tp, TIME["hasTRS"], TRS[a["trs"]]))
        g.add((tp, GEOLOD["ageKaBP"], Literal(a["ka"], datatype=XSD.decimal)))
        g.add((tp, GEOLOD["ageUncertaintyPos_ka"], Literal(a["unc"], datatype=XSD.decimal)))
        g.add((tp, GEOLOD["ageUncertaintyNeg_ka"], Literal(a["unc"], datatype=XSD.decimal)))
        g.add((tp, SKOS.note, Literal(f"Published as {a['published']}.", lang="en")))

        unc = GEOLOD[f"ci_eruption_unc_{a['id']}"]
        g.add((tp, GEOLOD["hasAgeUncertainty"], unc))
        g.add((unc, RDF.type, GEOLOD["AgeUncertainty"]))
        g.add((unc, RDFS.label, Literal(f"Uncertainty of {a['published']}", lang="en")))
        g.add((unc, GEOLOD["plusKa"], Literal(a["unc"], datatype=XSD.decimal)))
        g.add((unc, GEOLOD["minusKa"], Literal(a["unc"], datatype=XSD.decimal)))
        if a.get("coverage"):
            g.add((unc, GEOLOD["coverageLevel"], Literal(a["coverage"], datatype=XSD.decimal)))
        older = Decimal(a["ka"]) + Decimal(a["unc"])
        younger = Decimal(a["ka"]) - Decimal(a["unc"])
        interval = GEOLOD[f"ci_eruption_interval_{a['id']}"]
        g.add((unc, GEOLOD["hasAgeInterval"], interval))
        g.add((interval, RDF.type, TIME["ProperInterval"]))
        g.add((interval, RDFS.label, Literal(
            f"Age interval of {a['published']}, {younger} to {older} ka BP", lang="en")))
        for role, prop, value in (("begin", "hasBeginning", older), ("end", "hasEnd", younger)):
            inst = GEOLOD[f"ci_eruption_{role}_{a['id']}"]
            pos = GEOLOD[f"ci_eruption_{role}_pos_{a['id']}"]
            g.add((interval, TIME[prop], inst))
            g.add((inst, RDF.type, TIME["Instant"]))
            g.add((inst, TIME["inTimePosition"], pos))
            g.add((pos, RDF.type, TIME["TimePosition"]))
            g.add((pos, TIME["numericPosition"], Literal(value, datatype=XSD.decimal)))
            g.add((pos, TIME["hasTRS"], TRS[a["trs"]]))

        g.add((assertion, RDF.type, CRM["E13_Attribute_Assignment"]))
        g.add((assertion, RDF.type, PROV.Entity))
        g.add((assertion, RDFS.label, Literal(a["label"], lang="en")))
        g.add((assertion, RDFS.comment, Literal(a["note"], lang="en")))
        g.add((assertion, CRM["P140_assigned_attribute_to"], span))
        g.add((assertion, CRM["P141_assigned"], tp))
        g.add((assertion, PROV.wasDerivedFrom, article))
        g.add((assertion, DCTERMS.bibliographicCitation, Literal(a["citation"])))
        if a["adopted"]:
            g.add((span, GEOLOD["hasTimePosition"], tp))
            g.add((assertion, SKOS.note, Literal(
                "Adopted as the age of the event: the direct 40Ar/39Ar age of "
                "the eruption that Schenk et al. (2024) call the latest.",
                lang="en")))


def add_findspots(g: Graph, rows: list[dict], arch: set[str]) -> list[URIRef]:
    event = GEOLOD["ci_volcanic_event"]
    uris: list[URIRef] = []

    for row in rows:
        ci_id = text(row, "id")
        site = CI[f"cisite_{ci_id}"]
        geom = CI[f"cisite_{ci_id}_geom"]
        activity = CI[f"cisite_{ci_id}_activity"]
        script_run = CI[f"cisite_{ci_id}_pyscript"]
        uris.append(site)

        is_arch = ci_id in arch

        for cls in (GEOLOD["CIFindspot"], PROV.Entity, PLEIADES["Place"],
                    FSL["Site"]):
            g.add((site, RDF.type, cls))
        if is_arch:
            g.add((site, RDF.type, GEOLOD["CIArchaeologicalSite"]))
            g.add((site, RDF.type, CRMARCHAEO["A2_Stratigraphic_Volume_Unit"]))

        label = text(row, "label")
        if label:
            delivered = label
            label = LABEL_CORRECTIONS.get(label, label)
            g.add((site, RDFS.label, Literal(label, lang="en")))
            g.add((site, SKOS.prefLabel, Literal(label, lang="en")))
            if delivered != label:
                g.add((site, SKOS.altLabel, Literal(delivered, lang="en")))

        desc = text(row, "desc")
        if desc:
            g.add((site, SKOS.scopeNote, Literal(desc, lang="en")))
            g.add((site, RDFS.comment, Literal(desc, lang="en")))

        certainty = text(row, "certainty")
        certainty_info = text(row, "certaintyinfo")
        if certainty:
            g.add((site, GEOLOD["hasCertaintyLevel"], expand(certainty)))
        if certainty_info:
            g.add((site, GEOLOD["hasCertaintyDescription"],
                   Literal(certainty_info, lang="en")))

        for spatial_type in split(text(row, "spatialtype")):
            g.add((site, GEOLOD["hasSpatialType"], expand(spatial_type)))

        literature = split(text(row, "literature"))
        for reference in literature:
            g.add((site, GEOLOD["hasLiteratureReference"], Literal(reference)))

        related = text(row, "relatedto")
        related_how = text(row, "relatedtohow")
        if related and related_how:
            predicate = expand(related_how)
            for target in split(related):
                if target.startswith("http"):
                    g.add((site, predicate, URIRef(target)))

        # Every findspot is a place where the tephra is present. That the
        # eruption reached an archaeological site is stated by the site's own
        # type, not by a second, stronger property: P7 would put the eruption
        # at the site.
        g.add((event, CRM["P12_occurred_in_the_presence_of"], site))

        wkt = text(row, "wkt")
        if wkt:
            g.add((site, GEO["hasGeometry"], geom))
            g.add((geom, RDF.type, SF["Point"]))
            g.add((geom, RDF.type, CRMGEO["SP6_Declarative_Place"]))
            g.add((geom, GEO["asWKT"], wkt_literal(wkt)))
            if certainty:
                g.add((geom, GEOLOD["hasCertaintyLevel"], expand(certainty)))
            if certainty_info:
                g.add((geom, GEOLOD["hasCertaintyDescription"],
                       Literal(certainty_info, lang="en")))

        agents = []
        for orcid in split(text(row, "agent")):
            if orcid.startswith("http"):
                agent = URIRef(orcid)
                g.add((agent, RDF.type, FOAF["Person"]))
                g.add((agent, RDF.type, PROV.Agent))
                agents.append(agent)

        method = text(row, "methodtype")
        if method:
            g.add((activity, RDF.type, PROV.Activity))
            g.add((activity, RDF.type, expand(method)))
        source = text(row, "source")
        if source:
            g.add((activity, FSL["hasSource"], expand(source)))
        source_type = text(row, "sourcetype")
        if source_type:
            g.add((activity, FSL["hasSourceType"], expand(source_type)))
        method_desc = text(row, "methoddesc")
        if method_desc:
            g.add((activity, FSL["activityDesc"],
                   Literal(method_desc, lang="en")))
        for reference in literature:
            g.add((activity, GEOLOD["hasLiteratureReference"],
                   Literal(reference)))
        if certainty:
            g.add((activity, GEOLOD["hasCertaintyLevel"], expand(certainty)))

        # The georeferencing produced the coordinates, not the place: a
        # findspot exists whether or not anyone has put a point on it.
        if wkt:
            g.add((geom, PROV.wasGeneratedBy, activity))
        for agent in agents:
            g.add((site, PROV.wasAttributedTo, agent))
            g.add((activity, PROV.wasAssociatedWith, agent))

        g.add((site, PROV.wasGeneratedBy, script_run))
        g.add((site, PROV.wasAttributedTo, CI_SOURCE_SCRIPT))
        g.add((site, PROV.wasDerivedFrom, CI_SOURCE_REPO))
        g.add((script_run, RDF.type, PROV.Activity))
        g.add((script_run, PROV.wasAssociatedWith, CI_SOURCE_SCRIPT))

        g.add((site, DCTERMS.license, CI_LICENSE))
        for who in (ORCID_FLO, ORCID_CO):
            g.add((site, DCTERMS.creator, who))
            g.add((site, DCTERMS.rightsHolder, who))

    return uris


